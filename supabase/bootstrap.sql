create or replace function public.nearby_courts(
  lat double precision,
  lon double precision,
  radius_m integer default 5000
)
returns table (court_id bigint, distance_m integer)
language plpgsql stable security invoker set search_path = public, extensions, gis
as $$
begin
  if lat not between -90 and 90 or lon not between -180 and 180 then
    raise exception 'Coordinates are out of range';
  end if;
  if radius_m not between 1 and 100000 then
    raise exception 'Radius must be between 1 and 100000 meters';
  end if;
  return query
    select c.id, round(st_distance(
      c.location,
      st_setsrid(st_makepoint(lon, lat), 4326)::geography
    ))::integer
    from public.courts c
    where st_dwithin(
      c.location,
      st_setsrid(st_makepoint(lon, lat), 4326)::geography,
      radius_m
    )
    order by 2;
end;
$$;

create or replace function public.verify_court(
  target_court_id bigint,
  confirmed boolean default true,
  verification_comment text default ''
)
returns public.court_verifications
language plpgsql security definer set search_path = ''
as $$
declare
  profile_id bigint := public.current_profile_id();
  result public.court_verifications;
begin
  if profile_id is null then raise exception 'Authentication required'; end if;
  if char_length(verification_comment) > 1000 then raise exception 'Comment is too long'; end if;
  perform pg_advisory_xact_lock(target_court_id);
  if exists (
    select 1 from public.court_verifications
    where court_id = target_court_id and user_id = profile_id
      and created_at >= now() - interval '14 days'
  ) then
    raise exception 'Court was already verified recently';
  end if;
  insert into public.court_verifications(court_id, user_id, is_confirmed, comment)
  values (target_court_id, profile_id, confirmed, verification_comment)
  returning * into result;
  if confirmed then
    update public.courts set verified_at = now() where id = target_court_id;
  end if;
  return result;
end;
$$;

create or replace function public.create_game(
  target_court_id bigint,
  game_title text,
  game_description text,
  game_starts_at timestamptz,
  game_ends_at timestamptz,
  game_skill_level text,
  game_max_players integer
)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare
  profile_id bigint := public.current_profile_id();
  game_id bigint;
begin
  if profile_id is null then raise exception 'Authentication required'; end if;
  if not exists (select 1 from public.courts where id = target_court_id and status = 'published') then
    raise exception 'Published court not found';
  end if;
  if char_length(game_title) not between 3 and 180 then raise exception 'Invalid title'; end if;
  if char_length(coalesce(game_description, '')) > 3000 then raise exception 'Description is too long'; end if;
  if game_ends_at <= game_starts_at then raise exception 'End must be after start'; end if;
  if game_skill_level not in ('any', 'beginner', 'intermediate', 'advanced') then
    raise exception 'Invalid skill level';
  end if;
  if game_max_players not between 2 and 100 then raise exception 'Invalid player limit'; end if;
  insert into public.games(
    court_id, creator_id, title, description, starts_at, ends_at, skill_level, max_players
  ) values (
    target_court_id, profile_id, game_title, coalesce(game_description, ''),
    game_starts_at, game_ends_at, game_skill_level, game_max_players
  ) returning id into game_id;
  insert into public.game_participants(game_id, user_id) values (game_id, profile_id);
  return game_id;
end;
$$;

create or replace function public.join_game(target_game_id bigint)
returns void language plpgsql security definer set search_path = ''
as $$
declare
  profile_id bigint := public.current_profile_id();
  selected_game public.games;
  joined_count integer;
begin
  if profile_id is null then raise exception 'Authentication required'; end if;
  select * into selected_game from public.games where id = target_game_id for update;
  if selected_game.id is null or selected_game.status <> 'scheduled' or selected_game.starts_at <= now() then
    raise exception 'Game cannot be joined';
  end if;
  select count(*) into joined_count from public.game_participants
    where game_id = target_game_id and status = 'joined';
  if joined_count >= selected_game.max_players then raise exception 'Game is full'; end if;
  if exists (
    select 1 from public.game_participants
    where game_id = target_game_id and user_id = profile_id and status = 'joined'
  ) then raise exception 'Already joined'; end if;
  insert into public.game_participants(game_id, user_id, status, joined_at)
  values (target_game_id, profile_id, 'joined', now())
  on conflict (game_id, user_id) do update set status = 'joined', joined_at = now();
end;
$$;

create or replace function public.leave_game(target_game_id bigint)
returns void language plpgsql security definer set search_path = ''
as $$
declare
  profile_id bigint := public.current_profile_id();
begin
  if profile_id is null then raise exception 'Authentication required'; end if;
  if exists (select 1 from public.games where id = target_game_id and creator_id = profile_id) then
    raise exception 'Creator must cancel the game';
  end if;
  update public.game_participants set status = 'left'
    where game_id = target_game_id and user_id = profile_id and status = 'joined';
  if not found then raise exception 'Not joined'; end if;
end;
$$;

create or replace function public.update_game(
  target_game_id bigint,
  game_title text,
  game_description text,
  game_starts_at timestamptz,
  game_ends_at timestamptz,
  game_skill_level text,
  game_max_players integer
)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare
  profile_id bigint := public.current_profile_id();
  selected_game public.games;
  joined_count integer;
begin
  if profile_id is null then raise exception 'Authentication required'; end if;
  select * into selected_game
  from public.games
  where id = target_game_id
  for update;
  if selected_game.id is null then raise exception 'Game not found'; end if;
  if selected_game.creator_id <> profile_id and not public.is_moderator() then
    raise exception 'Game management forbidden';
  end if;
  if selected_game.status <> 'scheduled' or selected_game.starts_at <= now() then
    raise exception 'Game cannot be edited';
  end if;
  if char_length(game_title) not between 3 and 180 then
    raise exception 'Invalid title';
  end if;
  if char_length(coalesce(game_description, '')) > 3000 then
    raise exception 'Description is too long';
  end if;
  if game_starts_at <= now() or game_ends_at <= game_starts_at then
    raise exception 'Invalid game schedule';
  end if;
  if game_skill_level not in ('any', 'beginner', 'intermediate', 'advanced') then
    raise exception 'Invalid skill level';
  end if;
  if game_max_players not between 2 and 100 then
    raise exception 'Invalid player limit';
  end if;
  select count(*) into joined_count
  from public.game_participants
  where game_id = target_game_id and status = 'joined';
  if game_max_players < joined_count then
    raise exception 'Player limit is below participant count';
  end if;

  update public.games
  set
    title = game_title,
    description = coalesce(game_description, ''),
    starts_at = game_starts_at,
    ends_at = game_ends_at,
    skill_level = game_skill_level,
    max_players = game_max_players
  where id = target_game_id;
  return target_game_id;
end;
$$;

create or replace function public.cancel_game(target_game_id bigint)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare
  profile_id bigint := public.current_profile_id();
  selected_game public.games;
begin
  if profile_id is null then raise exception 'Authentication required'; end if;
  select * into selected_game
  from public.games
  where id = target_game_id
  for update;
  if selected_game.id is null then raise exception 'Game not found'; end if;
  if selected_game.creator_id <> profile_id and not public.is_moderator() then
    raise exception 'Game management forbidden';
  end if;
  if selected_game.status = 'cancelled' then return target_game_id; end if;
  if selected_game.ends_at <= now() then raise exception 'Game has finished'; end if;
  update public.games set status = 'cancelled' where id = target_game_id;
  return target_game_id;
end;
$$;

create or replace function public.claim_game_reminders(
  target_now timestamptz default now()
)
returns table (
  delivery_id bigint,
  game_id bigint,
  user_id bigint,
  reminder_kind text,
  game_title text,
  starts_at timestamptz,
  court_name text
)
language sql
security definer
set search_path = ''
as $$
  with recipients as (
    select
      game.id as game_id,
      game.creator_id as user_id,
      game.title,
      game.starts_at,
      court.name as court_name
    from public.games game
    join public.courts court on court.id = game.court_id
    where game.status = 'scheduled'
    union
    select
      game.id,
      participant.user_id,
      game.title,
      game.starts_at,
      court.name
    from public.games game
    join public.courts court on court.id = game.court_id
    join public.game_participants participant
      on participant.game_id = game.id and participant.status = 'joined'
    where game.status = 'scheduled'
  ),
  due as (
    select
      recipient.*,
      case
        when recipient.starts_at between target_now + interval '1 hour 45 minutes'
          and target_now + interval '2 hours 15 minutes' then '2h'
        when recipient.starts_at between target_now + interval '23 hours 45 minutes'
          and target_now + interval '24 hours 15 minutes' then '24h'
      end as reminder_kind
    from recipients recipient
  ),
  allowed as (
    select due.*
    from due
    left join public.notification_preferences preference
      on preference.user_id = due.user_id
    where due.reminder_kind is not null
      and coalesce(preference.game_reminders, true)
      and (
        (due.reminder_kind = '24h' and coalesce(preference.reminder_24h, true))
        or
        (due.reminder_kind = '2h' and coalesce(preference.reminder_2h, true))
      )
  ),
  claimed as (
    insert into public.game_reminder_deliveries(
      game_id,
      user_id,
      reminder_kind,
      claimed_at,
      last_error
    )
    select
      allowed.game_id,
      allowed.user_id,
      allowed.reminder_kind,
      target_now,
      ''
    from allowed
    on conflict (game_id, user_id, reminder_kind) do update
      set claimed_at = excluded.claimed_at, last_error = ''
      where public.game_reminder_deliveries.delivered_at is null
        and public.game_reminder_deliveries.claimed_at
          < target_now - interval '10 minutes'
    returning
      id,
      public.game_reminder_deliveries.game_id,
      public.game_reminder_deliveries.user_id,
      public.game_reminder_deliveries.reminder_kind
  )
  select
    claimed.id,
    claimed.game_id,
    claimed.user_id,
    claimed.reminder_kind,
    game.title,
    game.starts_at,
    court.name
  from claimed
  join public.games game on game.id = claimed.game_id
  join public.courts court on court.id = game.court_id
$$;

create or replace function public.consume_telegram_link(
  target_token_hash text,
  target_telegram_id bigint,
  telegram_username text default '',
  telegram_first_name text default '',
  telegram_last_name text default ''
)
returns table (linked_profile_id bigint, previous_auth_user_id uuid)
language plpgsql security definer set search_path = ''
as $$
declare
  target_profile_id bigint;
  source_profile_id bigint;
  source_auth_user_id uuid;
  source_auth_email text;
  target_record public.profiles;
  source_record public.profiles;
begin
  if target_token_hash !~ '^[a-f0-9]{64}$'
    or target_telegram_id <= 0
    or char_length(telegram_username) > 150
    or char_length(telegram_first_name) > 150
    or char_length(telegram_last_name) > 150 then
    raise exception 'Invalid account link';
  end if;

  select link.profile_id into target_profile_id
  from public.account_link_tokens link
  where link.token_hash = target_token_hash
    and link.consumed_at is null
    and link.expires_at > now()
  for update;
  if target_profile_id is null then
    raise exception 'Account link has expired';
  end if;

  select * into target_record
  from public.profiles
  where id = target_profile_id
  for update;
  if target_record.id is null then raise exception 'Target profile not found'; end if;
  if target_record.telegram_id is not null
    and target_record.telegram_id <> target_telegram_id then
    raise exception 'Another Telegram account is already linked';
  end if;

  select * into source_record
  from public.profiles
  where telegram_id = target_telegram_id
  for update;
  source_profile_id := source_record.id;

  if source_profile_id is not null and source_profile_id <> target_profile_id then
    source_auth_user_id := source_record.auth_user_id;
    select auth_user.email into source_auth_email
    from auth.users auth_user
    where auth_user.id = source_auth_user_id;
    if source_auth_email is null
      or source_auth_email !~ '^tg_[0-9]+@users\.hoopmap\.invalid$' then
      raise exception 'Telegram account is already linked';
    end if;

    insert into public.favorite_courts(user_id, court_id, created_at)
    select target_profile_id, court_id, created_at
    from public.favorite_courts
    where user_id = source_profile_id
    on conflict (user_id, court_id) do nothing;
    delete from public.favorite_courts where user_id = source_profile_id;

    delete from public.court_reviews source_review
    using public.court_reviews target_review
    where source_review.user_id = source_profile_id
      and target_review.user_id = target_profile_id
      and source_review.court_id = target_review.court_id;
    update public.court_reviews
      set user_id = target_profile_id
      where user_id = source_profile_id;

    insert into public.game_participants(game_id, user_id, status, joined_at)
    select game_id, target_profile_id, status, joined_at
    from public.game_participants
    where user_id = source_profile_id
    on conflict (game_id, user_id) do update set
      status = case
        when public.game_participants.status = 'joined'
          or excluded.status = 'joined' then 'joined'
        else 'left'
      end,
      joined_at = least(public.game_participants.joined_at, excluded.joined_at);
    delete from public.game_participants where user_id = source_profile_id;

    update public.courts set created_by = target_profile_id
      where created_by = source_profile_id;
    update public.court_photos set uploaded_by = target_profile_id
      where uploaded_by = source_profile_id;
    update public.court_reports set user_id = target_profile_id
      where user_id = source_profile_id;
    update public.court_verifications set user_id = target_profile_id
      where user_id = source_profile_id;
    update public.games set creator_id = target_profile_id
      where creator_id = source_profile_id;

    insert into public.push_subscriptions(
      user_id,
      endpoint,
      p256dh,
      auth,
      user_agent,
      created_at,
      updated_at,
      last_seen_at
    )
    select
      target_profile_id,
      endpoint,
      p256dh,
      auth,
      user_agent,
      created_at,
      updated_at,
      last_seen_at
    from public.push_subscriptions
    where user_id = source_profile_id
    on conflict (endpoint) do update set
      user_id = target_profile_id,
      p256dh = excluded.p256dh,
      auth = excluded.auth,
      user_agent = excluded.user_agent,
      last_seen_at = greatest(
        public.push_subscriptions.last_seen_at,
        excluded.last_seen_at
      );
    delete from public.push_subscriptions where user_id = source_profile_id;

    insert into public.notification_preferences(
      user_id,
      game_updates,
      game_reminders,
      reminder_24h,
      reminder_2h,
      created_at,
      updated_at
    )
    select
      target_profile_id,
      game_updates,
      game_reminders,
      reminder_24h,
      reminder_2h,
      created_at,
      updated_at
    from public.notification_preferences
    where user_id = source_profile_id
    on conflict (user_id) do nothing;
    delete from public.notification_preferences where user_id = source_profile_id;

    update public.profiles target
    set
      username = case
        when target.username like 'player\_%' escape '\'
          and source_record.username <> '' then source_record.username
        else target.username
      end,
      first_name = coalesce(nullif(target.first_name, ''), source_record.first_name),
      last_name = coalesce(nullif(target.last_name, ''), source_record.last_name),
      avatar_url = coalesce(nullif(target.avatar_url, ''), source_record.avatar_url),
      role = case
        when target.role = 'admin' or source_record.role = 'admin' then 'admin'
        when target.role = 'moderator' or source_record.role = 'moderator' then 'moderator'
        else 'user'
      end,
      reputation = greatest(target.reputation, source_record.reputation),
      map_home_lat = coalesce(target.map_home_lat, source_record.map_home_lat),
      map_home_lon = coalesce(target.map_home_lon, source_record.map_home_lon),
      map_home_consent_at = coalesce(
        target.map_home_consent_at,
        source_record.map_home_consent_at
      )
    where target.id = target_profile_id;

    delete from public.profiles where id = source_profile_id;
  end if;

  update public.profiles
  set
    telegram_id = target_telegram_id,
    username = case
      when username = '' and telegram_username <> '' then telegram_username
      else username
    end,
    first_name = coalesce(nullif(first_name, ''), telegram_first_name),
    last_name = coalesce(nullif(last_name, ''), telegram_last_name)
  where id = target_profile_id;

  update public.account_link_tokens
    set consumed_at = now()
    where token_hash = target_token_hash;
  delete from public.account_link_tokens
    where profile_id = target_profile_id
      and token_hash <> target_token_hash;
  delete from public.account_link_tokens
    where expires_at < now() - interval '1 day';

  return query select target_profile_id, source_auth_user_id;
end;
$$;

