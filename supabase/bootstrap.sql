create or replace function public.consume_rate_limit(
  target_key text,
  maximum_requests integer,
  window_seconds integer
)
returns boolean language plpgsql security definer set search_path = ''
as $$
declare
  current_bucket timestamptz;
  new_count integer;
begin
  if char_length(target_key) > 200 or maximum_requests not between 1 and 10000
    or window_seconds not between 1 and 86400 then
    raise exception 'Invalid rate limit';
  end if;
  current_bucket := to_timestamp(
    floor(extract(epoch from now()) / window_seconds) * window_seconds
  );
  insert into public.api_rate_limits(scope_key, bucket, request_count)
  values (target_key, current_bucket, 1)
  on conflict (scope_key, bucket) do update
    set request_count = public.api_rate_limits.request_count + 1
  returning request_count into new_count;
  delete from public.api_rate_limits where bucket < now() - interval '2 days';
  return new_count <= maximum_requests;
end;
$$;
revoke all on function public.consume_rate_limit(text, integer, integer) from public;
grant execute on function public.consume_rate_limit(text, integer, integer) to service_role;

